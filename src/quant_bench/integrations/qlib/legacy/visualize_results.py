#!/usr/bin/env python3
"""Utility to visualize hyperparameter sweep outcomes.

The script expects the CSV generated by ``hyperparam_sweep.py`` together with
the corresponding training logs. It extracts annualized return figures from the
logs, merges them with the sweep parameters, and produces several visuals:

1. Single-parameter response curves (others fixed at their center values).
2. Faceted panels with scatter, KDE density, and regression confidence bands.
3. A 2D heatmap snapshot for a selected parameter pair.
4. A correlation heatmap covering all numeric parameters plus returns.

Example::

	python visualize_results.py \
		--results hyper_runs/results.csv \
		--output-dir hyper_runs/plots \
		--base-config workflow/158/lgb/workflow_config_lgb_1m.yaml \
		--metric-target excess_with_cost

"""

from __future__ import annotations

import argparse
import re
from collections.abc import Iterable, Sequence
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import seaborn as sns
import yaml

sns.set_theme(style="whitegrid")

METRIC_PATTERNS = {
	"excess_with_cost": re.compile(
		r"excess return with cost.*?annualized_return\s+([\-\d\.eE]+)",
		re.IGNORECASE | re.DOTALL,
	),
	"excess_without_cost": re.compile(
		r"excess return without cost.*?annualized_return\s+([\-\d\.eE]+)",
		re.IGNORECASE | re.DOTALL,
	),
	"benchmark": re.compile(
		r"benchmark return.*?annualized_return\s+([\-\d\.eE]+)",
		re.IGNORECASE | re.DOTALL,
	),
}


def parse_args() -> argparse.Namespace:
	parser = argparse.ArgumentParser(description="Visualize hyperparameter sweep outcomes")
	parser.add_argument("--results", required=True, help="Path to sweep results CSV")
	parser.add_argument("--output-dir", default="hyper_runs/plots", help="Directory to store figures")
	parser.add_argument(
		"--base-config",
		default=None,
		help="Workflow YAML used to derive center values (optional but recommended)",
	)
	parser.add_argument(
		"--metric-target",
		choices=tuple(METRIC_PATTERNS.keys()),
		default="excess_with_cost",
		help="Which annualized_return block to extract from logs",
	)
	parser.add_argument(
		"--heatmap-params",
		nargs="+",
		metavar="PARAM",
		default=None,
		help="Subset of parameter names (>=2) to include in pairwise heatmaps. Default: all params.",
	)
	parser.add_argument(
		"--logs-root",
		default=None,
		help="Fallback directory if log paths inside CSV are relative",
	)
	return parser.parse_args()


def load_base_params(base_cfg: Path | None) -> dict[str, float]:
	if not base_cfg:
		return {}
	if not base_cfg.exists():
		raise FileNotFoundError(f"Base config not found: {base_cfg}")
	with open(base_cfg, encoding="utf-8") as fh:
		cfg = yaml.safe_load(fh)
	try:
		return cfg["task"]["model"].get("kwargs", {})
	except KeyError as exc:
		raise ValueError("Invalid config: missing task.model.kwargs") from exc


def _resolve_log_path(raw_path: str, logs_root: Path | None) -> Path:
	path = Path(raw_path)
	if path.is_file():
		return path
	if logs_root is not None:
		candidate = logs_root / path.name
		if candidate.is_file():
			return candidate
	return path


def extract_metric(log_path: Path, target: str) -> float | None:
	if not log_path.exists():
		print(f"[WARN] Log file missing: {log_path}")
		return None
	text = log_path.read_text(encoding="utf-8", errors="ignore")
	match = METRIC_PATTERNS[target].search(text)
	if not match:
		print(f"[WARN] Could not find '{target}' annualized_return in {log_path}")
		return None
	return float(match.group(1))


def determine_centers(df: pd.DataFrame, params: Iterable[str], base_params: dict[str, float]) -> dict[str, float]:
	centers: dict[str, float] = {}
	for param in params:
		if param in base_params:
			centers[param] = base_params[param]
			continue
		series = df[param].dropna()
		if series.empty:
			continue
		median_val = series.median()
		centers[param] = float(median_val)
	return centers


def compute_tolerances(df: pd.DataFrame, params: Sequence[str]) -> dict[str, float]:
	tolerances: dict[str, float] = {}
	for param in params:
		series = df[param].dropna().astype(float)
		if series.empty:
			continue
		uniques = np.sort(series.unique())
		if uniques.size >= 2:
			steps = np.diff(uniques)
			min_step = steps[steps > 0].min(initial=0.0)
		else:
			min_step = 0.0
		base_tol = max(abs(series.mean()) * 1e-6, 1e-8)
		if min_step > 0:
			tolerances[param] = max(base_tol, min_step / 2)
		else:
			tolerances[param] = base_tol
	return tolerances


def _is_close(series: pd.Series, target: float, tol: float) -> pd.Series:
	if np.isclose(tol, 0.0):
		if series.dtype.kind in {"i", "u"}:
			return series == int(round(target))
		return np.isclose(series, target, atol=1e-12)
	return np.isclose(series.astype(float), target, atol=tol)


def filter_by_centers(
	df: pd.DataFrame,
	focus_params: Sequence[str],
	centers: dict[str, float],
	tolerances: dict[str, float],
) -> pd.DataFrame:
	focus = set(focus_params)
	mask = pd.Series(True, index=df.index)
	for param, center in centers.items():
		if param in focus or param not in df.columns:
			continue
		tol = tolerances.get(param, 1e-8)
		mask &= _is_close(df[param], center, tol)
	return df.loc[mask]


def filter_single_param_slice(
	df: pd.DataFrame,
	param: str,
	centers: dict[str, float],
	other_params: list[str],
	tolerances: dict[str, float],
) -> pd.DataFrame:
	return filter_by_centers(df, [param], centers, tolerances)


def plot_single_param_curves(
	df: pd.DataFrame,
	params: list[str],
	centers: dict[str, float],
	tolerances: dict[str, float],
	out_dir: Path,
) -> pd.DataFrame:
	collected = []
	for param in params:
		subset = filter_single_param_slice(df, param, centers, params, tolerances)
		subset = subset.sort_values(param)
		if subset.empty:
			print(f"[WARN] Skipping '{param}' curve: no samples with other params fixed at centers.")
			continue
		plot_df = subset
		plt.figure(figsize=(6, 4))
		sns.scatterplot(data=plot_df, x=param, y="annualized_return", color="tab:blue", s=30)
		sns.lineplot(data=plot_df, x=param, y="annualized_return", color="tab:blue", marker="o")
		ax = plt.gca()
		x_vals = plot_df[param].to_numpy()
		y_vals = plot_df["annualized_return"].to_numpy()
		x_span = x_vals.max() - x_vals.min() if len(x_vals) else 0
		y_span = y_vals.max() - y_vals.min() if len(y_vals) else 0
		x_pad = 0.1 * x_span if x_span > 0 else max(abs(x_vals[0]) * 0.05, 1e-4) if len(x_vals) else 0.1
		y_pad = 0.1 * y_span if y_span > 0 else max(abs(y_vals[0]) * 0.2, 0.02) if len(y_vals) else 0.1
		if len(x_vals):
			ax.set_xlim(x_vals.min() - x_pad, x_vals.max() + x_pad)
		if len(y_vals):
			ax.set_ylim(y_vals.min() - y_pad, y_vals.max() + y_pad)
		plt.title(f"Single-parameter response: {param}")
		plt.xlabel(param)
		plt.ylabel("Annualized Return")
		plt.tight_layout()
		outfile = out_dir / f"single_curve_{param}.png"
		plt.savefig(outfile, dpi=200)
		plt.close()
		collected.append(
			plot_df[[param, "annualized_return"]]
			.assign(
				param_name=param,
				param_value=lambda d: d[param],
				param_delta=lambda d: d[param] - centers.get(param, d[param].median()),
				point_type="center_slice",
			)
			.loc[:, ["param_value", "param_delta", "annualized_return", "param_name", "point_type"]]
		)
	if collected:
		collected_df = pd.concat(collected, ignore_index=True)
		return collected_df
	return pd.DataFrame(columns=["param_value", "param_delta", "annualized_return", "param_name", "point_type"])


def collect_top_points(
	df: pd.DataFrame,
	single_param_df: pd.DataFrame,
	params: list[str],
	centers: dict[str, float],
	tolerances: dict[str, float],
	top_k: int = 5,
) -> tuple[pd.DataFrame, pd.DataFrame]:
	if single_param_df.empty:
		return pd.DataFrame(), pd.DataFrame()
	plot_records: list[dict] = []
	detail_records: list[dict] = []
	for param in params:
		param_slice = single_param_df[single_param_df["param_name"] == param]
		if param_slice.empty or param not in df.columns:
			continue
		tol = tolerances.get(param, 1e-8)
		for value in param_slice["param_value"].unique():
			matching = df[np.isclose(df[param], value, atol=tol)]
			if matching.empty:
				continue
			top_rows = matching.sort_values("annualized_return", ascending=False).head(top_k)
			for _, row in top_rows.iterrows():
				plot_records.append(
					{
						"param_name": param,
						"param_value": value,
						"param_delta": value - centers.get(param, value),
						"annualized_return": row["annualized_return"],
						"point_type": "top_k",
					}
				)
				detail = {
					"param_name": param,
					"param_value": value,
					"annualized_return": row["annualized_return"],
					"cfg_path": row.get("cfg_path"),
					"log_path": row.get("log_path"),
				}
				for other in params:
					detail[other] = row.get(other)
				detail_records.append(detail)
	plot_df = pd.DataFrame(plot_records)
	detail_df = pd.DataFrame(detail_records)
	return plot_df, detail_df


def plot_facet_panel(facet_df: pd.DataFrame, out_dir: Path, centers: dict[str, float]) -> None:
	"""Create faceted panel from combined single_param_df and top_points_df.

	Each parameter gets its own subplot with appropriate coordinate scaling.
	Overlays top-k red X markers.
	"""
	if facet_df.empty:
		return

	param_names = facet_df["param_name"].unique()
	num_params = len(param_names)
	num_cols = 3
	num_rows = (num_params + num_cols - 1) // num_cols

	fig, axes = plt.subplots(num_rows, num_cols, figsize=(15, 4 * num_rows))
	if num_params == 1:
		axes = np.array([axes])
	else:
		axes = axes.flatten()

	for idx, param in enumerate(param_names):
		ax = axes[idx]
		param_data = facet_df[facet_df["param_name"] == param]

		center = param_data[param_data["point_type"] == "center_slice"]
		extra = param_data[param_data["point_type"] == "top_k"]

		# Plot center slice
		if not center.empty:
			center_sorted = center.sort_values("param_value")
			ax.scatter(center_sorted["param_value"], center_sorted["annualized_return"], color="tab:blue", s=30, alpha=0.7, zorder=3)
			ax.plot(center_sorted["param_value"], center_sorted["annualized_return"], color="tab:blue", marker="o", zorder=2)

		# Plot top-k points
		if not extra.empty:
			ax.scatter(extra["param_value"], extra["annualized_return"], marker="X", color="crimson", s=100, edgecolor="black", linewidth=0.4, zorder=4)

		# Apply adaptive scaling
		x_vals_center = center["param_value"].to_numpy() if not center.empty else np.array([])
		y_vals_center = center["annualized_return"].to_numpy() if not center.empty else np.array([])
		x_vals_all = np.concatenate([x_vals_center, extra["param_value"].to_numpy()]) if not extra.empty else x_vals_center
		y_vals_all = np.concatenate([y_vals_center, extra["annualized_return"].to_numpy()]) if not extra.empty else y_vals_center

		if len(x_vals_all) > 0:
			x_span = x_vals_all.max() - x_vals_all.min()
			y_span = y_vals_all.max() - y_vals_all.min()
			x_pad = 0.1 * x_span if x_span > 0 else max(abs(x_vals_all[0]) * 0.05, 1e-4)
			y_pad = 0.1 * y_span if y_span > 0 else max(abs(y_vals_all[0]) * 0.2, 0.02)
			ax.set_xlim(x_vals_all.min() - x_pad, x_vals_all.max() + x_pad)
			ax.set_ylim(y_vals_all.min() - y_pad, y_vals_all.max() + y_pad)

		ax.set_title(f"param_name = {param}", fontsize=11)
		ax.set_xlabel(param)
		ax.set_ylabel("Annualized Return")
		ax.grid(True, alpha=0.3)

	# Hide unused subplots
	for idx in range(num_params, len(axes)):
		axes[idx].set_visible(False)

	plt.tight_layout()
	outfile = out_dir / "facet_ci_density.png"
	fig.savefig(outfile, dpi=220)
	plt.close(fig)


def plot_pair_heatmaps(
	df: pd.DataFrame,
	params: list[str],
	centers: dict[str, float],
	tolerances: dict[str, float],
	out_dir: Path,
	subset: Sequence[str] | None,
) -> None:
	from itertools import combinations

	usable = [p for p in (subset or params) if p in params]
	if len(usable) < 2:
		return
	for p1, p2 in combinations(usable, 2):
		pair_df = filter_by_centers(df, [p1, p2], centers, tolerances)
		if pair_df.empty:
			print(f"[WARN] Skipping heatmap {p1}-{p2}: no samples at center for other params")
			continue
		pivot = (
			pair_df.groupby([p1, p2])["annualized_return"].mean().reset_index().pivot(index=p2, columns=p1, values="annualized_return")
		)
		plt.figure(figsize=(6, 5))
		sns.heatmap(pivot, annot=True, fmt=".3f", cmap="RdYlGn", cbar_kws={"label": "Annualized Return"})
		plt.title(f"Heatmap: {p1} vs {p2}")
		plt.xlabel(p1)
		plt.ylabel(p2)
		plt.tight_layout()
		outfile = out_dir / f"heatmap_{p1}_vs_{p2}.png"
		plt.savefig(outfile, dpi=220)
		plt.close()


def plot_correlation_heatmap(df: pd.DataFrame, params: list[str], out_dir: Path) -> None:
	corr_cols = [col for col in params if col in df.columns]
	if not corr_cols:
		print("[WARN] No parameter columns available for correlation heatmap")
		return
	base_df = df[corr_cols + ["annualized_return"]].apply(pd.to_numeric, errors="coerce").dropna()
	base_df = base_df.loc[:, base_df.nunique() > 1]
	if "annualized_return" not in base_df.columns:
		print("[WARN] Insufficient data for correlation heatmap")
		return
	param_cols = [c for c in corr_cols if c in base_df.columns]
	if not param_cols:
		print("[WARN] Parameter columns constant; skipping correlation heatmap")
		return
	# Compute full Spearman correlation matrix including all parameters and annualized_return
	corr = base_df[param_cols + ["annualized_return"]].corr(method="spearman")
	plt.figure(figsize=(6, 5))
	sns.heatmap(corr, annot=True, fmt=".3f", cmap="coolwarm", vmin=-1, vmax=1, square=True, cbar_kws={"label": "Spearman Correlation"})
	plt.title("Correlation heatmap (Spearman) - All Parameters vs Annualized Return")
	plt.tight_layout()
	outfile = out_dir / "correlation_heatmap.png"
	plt.savefig(outfile, dpi=220)
	plt.close()


def main() -> None:
	args = parse_args()
	out_dir = Path(args.output_dir)
	out_dir.mkdir(parents=True, exist_ok=True)

	logs_root = Path(args.logs_root) if args.logs_root else None
	df = pd.read_csv(args.results)
	df["log_path"] = df["log_path"].apply(lambda p: str(_resolve_log_path(p, logs_root)))
	df["log_path"] = df["log_path"].apply(Path)

	df["annualized_return"] = df["log_path"].apply(lambda p: extract_metric(p, args.metric_target))
	df = df.dropna(subset=["annualized_return"])
	if df.empty:
		raise RuntimeError("No rows with extractable annualized_return. Check logs and metric target.")

	numeric_cols = df.select_dtypes(include=["number"]).columns.tolist()
	param_cols = [col for col in numeric_cols if col not in {"return_code", "annualized_return"}]
	if not param_cols:
		raise RuntimeError("No numeric parameter columns found in results CSV.")

	base_params = load_base_params(Path(args.base_config)) if args.base_config else {}
	centers = determine_centers(df, param_cols, base_params)

	print("Center values used:")
	for k, v in centers.items():
		print(f"  - {k}: {v}")

	tolerances = compute_tolerances(df, param_cols)
	single_param_df = plot_single_param_curves(df, param_cols, centers, tolerances, out_dir)
	top_points_df, detail_df = collect_top_points(df, single_param_df, param_cols, centers, tolerances)
	if not detail_df.empty:
		detail_path = out_dir / "top_points_details.csv"
		detail_df.to_csv(detail_path, index=False)
	if not df.empty:
		n_top = max(1, int(len(df) * 0.05))
		df.nlargest(n_top, "annualized_return").to_csv(out_dir / "top5_percent_combos.csv", index=False)
	combined_facet_df = pd.concat([single_param_df, top_points_df], ignore_index=True) if not top_points_df.empty else single_param_df
	plot_facet_panel(combined_facet_df, out_dir, centers)
	plot_pair_heatmaps(df, param_cols, centers, tolerances, out_dir, args.heatmap_params)
	plot_correlation_heatmap(df, param_cols, out_dir)

	print(f"Visualization complete. Figures saved to {out_dir}")


if __name__ == "__main__":
	main()
